export const INDIA_STATES = Object.keys(INDIA_LOCATIONS).sort((a, b) =>
    a.localeCompare(b)
);

export function getCitiesForState(state: string): string[] {
    return INDIA_LOCATIONS[state] ? [...INDIA_LOCATIONS[state]].sort((a, b) => a.localeCompare(b)) : [];
}

export function normalizeLocationName(value: string): string {
    return value
        .toLowerCase()
        .trim()
        .replace(/\s+/g, ' ')
        .replace(/bangalore/g, 'bengaluru')
        .replace(/bombay/g, 'mumbai')
        .replace(/madras/g, 'chennai')
        .replace(/calcutta/g, 'kolkata')
        .replace(/poona/g, 'pune')
        .replace(/gurgaon/g, 'gurugram')
        .replace(/trivandrum/g, 'thiruvananthapuram')
        .replace(/baroda/g, 'vadodara')
        .replace(/benares|banaras/g, 'varanasi')
        .replace(/allahabad/g, 'prayagraj');
}

