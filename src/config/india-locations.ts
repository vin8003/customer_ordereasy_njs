/** Match IP / free-text region to a known state name (exact → alias → careful prefix). */
export function matchState(region: string | null | undefined): string | null {
    if (!region) return null;
    const n = normalizeLocationName(region);

    for (const state of INDIA_STATES) {
        if (normalizeLocationName(state) === n) return state;
    }

    if (STATE_ALIASES[n]) return STATE_ALIASES[n];

    // Prefix only when query is long enough to avoid short false positives (e.g. "or")
    if (n.length >= 4) {
        for (const state of INDIA_STATES) {
            const ns = normalizeLocationName(state);
            if (ns.startsWith(n) || (n.length >= 6 && n.startsWith(ns))) return state;
        }
    }
    return null;
}

/** Match city within a state; exact first, then careful prefix (min 4 chars). */
export function matchCity(city: string | null | undefined, state: string | null): string | null {
    if (!city || !state) return null;
    const cities = getCitiesForState(state);
    const n = normalizeLocationName(city);

    for (const c of cities) {
        if (normalizeLocationName(c) === n) return c;
    }
    if (n.length >= 4) {
        for (const c of cities) {
            const nc = normalizeLocationName(c);
            if (nc.startsWith(n) || (n.length >= 6 && n.startsWith(nc))) return c;
        }
    }
    return null;
}

export function cityId(name: string, state: string): string {
    return `${normalizeLocationName(name).replace(/\s+/g, '-')}_${normalizeLocationName(state).replace(/\s+/g, '-')}`;
}
